"""О данных и методика: происхождение данных, допущения, формулы, проверки качества, подключение источников."""

from __future__ import annotations

import pandas as pd
import streamlit as st

from bi import config as C
from bi import queries as Q
from bi import ui


def render(f: Q.Filters):
    ui.page_header("О данных и методика", "Что здесь факт, что допущение и как считаются показатели", None, "about")

    st.warning(
        "**Все операционные данные синтетические.** Структура сетей (число магазинов, склады и РЦ, регионы, темпы "
        "открытий, отдельные параметры промо и лояльности) взята из открытых источников; продажи, остатки, поставки и "
        "рейсы сгенерированы моделью. Цифры не отражают реальные результаты компаний.", icon=":material/science:")
    if not C.show_real_names():
        st.caption("Названия сетей обезличены: «Сеть А» — формат супермаркетов у дома (~100 магазинов, Ульяновская и "
                   "Саратовская обл., 1 РЦ), «Сеть Б» — дискаунтеры (~860 магазинов, 6 РЦ). Реальные названия включаются "
                   "настройкой SHOW_REAL_NAMES=1.")

    t1, t2, t3, t4, t5 = st.tabs(["Источники и допущения", "Модель данных", "Формулы", "Качество данных", "Подключение"])

    with t1:
        st.markdown("#### Открытые источники")
        st.dataframe(pd.DataFrame(C.SOURCES, columns=["Источник", "Ссылка", "Что взято"]), hide_index=True,
                     column_config={"Ссылка": st.column_config.LinkColumn(width="medium"),
                                    "Что взято": st.column_config.TextColumn(width="large")})
        st.markdown("#### Параметры генерации")
        rows = [
            ("Сеть А: магазинов на начало / конец", f"{C.CHAINS['G']['stores_start']} / {C.CHAINS['G']['stores_end']}", "Факт (Retail.ru) / расчёт: + 3 открытия в 2026 (интервью)"),
            ("Сеть Б: магазинов на начало / конец", f"{C.CHAINS['P']['stores_start']} / {C.CHAINS['P']['stores_end']}", "Факт (сайт сети) / расчёт: + ~100 открытий в год"),
            ("РЦ", "1 у сети А, 6 у сети Б; в каждом РЦ — 5 складов по температурным зонам",
             "5 РЦ сети Б и их города — факт (сайт сети); 6-й РЦ (условно Тула), РЦ сети А и состав складов — допущение"),
            ("Оргструктура", "Сеть → федеральный округ → дивизион → УГМ (~10 магазинов) → магазин",
             "Федеральные округа — факт; дивизионы, УГМ и закрепление за РЦ — допущение"),
            ("Брак при приёмке, сроки годности, декларации", "см. bi/config.py", "Допущение"),
            ("Регионы сети Б", f"{len(C.P_REGIONS)} регионов", "Факт (список адресов); распределение магазинов — допущение"),
            ("Чеков в день на магазин, сеть Б", str(C.CHAINS['P']['checks_per_day']), "Расчёт: 182 млн посещений в 2024 г. / ~620 магазинов / 365 дней"),
            ("Чеков в день на магазин, сеть А", str(C.CHAINS['G']['checks_per_day']), "Допущение"),
            ("Средний чек 2025, сеть А / Б", f"{C.CHAINS['G']['avg_check']:.0f} / {C.CHAINS['P']['avg_check']:.0f} ₽", "Допущение"),
            ("Рост цен г/г", ui.pct(C.PRICE_INFLATION, 0), "Допущение"),
            ("Скидка в промо, сеть А / Б", f"{C.CHAINS['G']['promo_discount']:.0%} / {C.CHAINS['P']['promo_discount']:.0%}", "Факт: интервью (15–20%) / новости сайта («минус 10%»)"),
            ("Рост продаж в акции, сеть А", f"×{C.CHAINS['G']['promo_uplift']}", "Факт: интервью (в 4–5 раз)"),
            ("Чеки с картой лояльности, сеть А", ui.pct(C.CHAINS['G']['loyalty_share'], 0), "Факт: интервью"),
            ("Доставка, сеть А", f"{C.CHAINS['G']['delivery_stores']} магазинов, ~{C.CHAINS['G']['delivery_orders_day']} заказов в день, +40% в год", "Факт: интервью"),
            ("Доли, маржа, списания, нормативы запаса категорий", "см. bi/config.py", "Допущение"),
            ("Поставщики, сроки и надёжность", f"{C.N_SUPPLIERS} поставщиков", "Допущение"),
        ]
        st.dataframe(pd.DataFrame(rows, columns=["Параметр", "Значение", "Основание"]), hide_index=True,
                     height=38 + 35 * len(rows))
        st.markdown("#### Заложенные закономерности")
        st.markdown(
            "Чтобы на данных было что анализировать, в генератор намеренно заложены четыре сценария. "
            "Их находит аналитика — это проверка, что дашборд показывает отклонения, а не «ровную картинку».\n\n"
            "1. С апреля 2026 в Самарской обл. у сети Б снижается трафик (условный новый конкурент).\n"
            "2. Летом 2026 у РЦ Краснодар падает пунктуальность поставщиков и рейсов, растёт брак → растёт дефицит.\n"
            "3. В августе растут списания и брак овощей и фруктов.\n"
            "4. Около 5% SKU выводятся из матрицы, но остатки на РЦ остаются → неликвид.\n"
            "5. С 01.01.2026 магазины сети Б в Саратовской обл. переведены в другой дивизион, часть магазинов сменила "
            "УГМ или наименование → проверка пересчёта истории по текущей структуре.\n"
            "6. Два поставщика с повышенным браком; несколько деклараций истекают или уже истекли.")

    with t2:
        st.markdown(
            "| Таблица | Детализация | Содержание |\n|---|---|---|\n"
            "| `dim_store` | магазин | сеть, федеральный округ, дивизион, УГМ, регион, город, РЦ, формат, дата открытия |\n"
            "| `dim_store_history` | изменение атрибута | дата, атрибут, было / стало (наименование, УГМ, дивизион) |\n"
            "| `dim_dc`, `dim_warehouse` | РЦ, склад | сеть, город; склады РЦ по температурным зонам |\n"
            "| `dim_certificate` | документ | декларация / сертификат, номер (условный), срок действия |\n"
            "| `meta_dataset` | витрина | источник, регламент обновления, время последней загрузки |\n"
            "| `dim_category` | категория | маржа, норматив запаса, свежая/нет |\n"
            "| `dim_sku`, `dim_supplier` | SKU, поставщик | категория, поставщик, цена, себестоимость, упаковка, СТМ |\n"
            "| `fact_store_day` | день × магазин | чеки, чеки с картой, заказы доставки, выручка |\n"
            "| `fact_sales` | день × магазин × категория | РТО, себестоимость, штуки, РТО и себестоимость в промо, списания, остаток, доля дефицита |\n"
            "| `fact_plan` | месяц × магазин | план выручки |\n"
            "| `fact_sku_dc` | день × склад × SKU | спрос, отгрузка в магазины, приход, остаток, признак акции |\n"
            "| `fact_supplier_order` | заказ поставщику | даты заказа, обещания и прихода, заказано / принято / брак |\n"
            "| `fact_delivery` | рейс склад → магазин | плановое и фактическое время, отгружено / принято |\n")
        st.caption("В целевой системе детализация продаж — до «товар – день – подразделение». Здесь для магазинов "
                   "она ограничена категорией, чтобы приложение работало без сервера БД; SKU-уровень показан на складах.")
        sizes = Q.data_quality()
        rows_ = sizes[sizes["Проверка"] == "Строк"][["Таблица", "Значение"]].rename(columns={"Значение": "Строк"})
        st.dataframe(rows_, hide_index=True, column_config={"Строк": st.column_config.NumberColumn(format="localized")})

    with t3:
        st.markdown(
            "| Показатель | Формула |\n|---|---|\n"
            "| Выручка | сумма продаж в розничных ценах |\n"
            "| Валовая маржа | (выручка − себестоимость продаж) / выручка |\n"
            "| LFL | изменение выручки магазинов, открытых не позже чем за 364 дня до начала периода, к тому же периоду год назад |\n"
            "| Сравнение с прошлым годом | тот же период со сдвигом 364 дня — совпадают дни недели |\n"
            "| Средний чек | выручка магазинов / число чеков |\n"
            "| Выполнение плана | выручка / план; месячный план распределяется по дням периода |\n"
            "| Дефицит (OOS) | доля позиций без остатка на полке, взвешенная по выручке |\n"
            "| Запас, дней | средний остаток в себестоимости / средняя дневная себестоимость продаж |\n"
            "| Списания | списания / себестоимость продаж |\n"
            "| ABC | A — позиции, дающие первые 80% результата, B — следующие 15%, C — остальные |\n"
            "| XYZ | коэффициент вариации недельных продаж: X ≤ 0,25, Y ≤ 0,5, Z — выше (границы настраиваются) |\n"
            "| Страховой запас | z × √(LT × σ²спроса + спрос² × σ²LT) |\n"
            "| Точка заказа | спрос × LT + страховой запас |\n"
            "| OTIF | доля заказов, пришедших не позже обещанной даты и в объёме ≥ 98% заказанного |\n"
            "| Рейс в окне | прибытие не позже чем через 30 минут после планового времени |\n"
            "| Прогноз | та же неделя прошлого года × темп последних 8 недель к прошлому году; интервал — по ошибкам за 26 недель |\n")
        st.caption("В целевой системе формулы приводятся к методологии компании. "
                   "Каждая формула — отдельная функция в bi/metrics.py с тестами.")

    with t4:
        st.markdown("Автоматические проверки, которые выполняются над источником при каждом обновлении данных:")
        st.dataframe(Q.data_quality(), hide_index=True,
                     column_config={"Значение": st.column_config.NumberColumn(format="localized")})

    with t5:
        st.markdown(f"Сейчас подключено: **{Q.backend().name}**.")
        st.markdown(
            "**MySQL.** Загрузить данные: `python scripts/load_mysql.py --url mysql+pymysql://user:pass@host:3306/retail_bi`. "
            "Затем задать в `.streamlit/secrets.toml` или переменных окружения:\n"
            "```toml\nDATA_BACKEND = \"mysql\"\nMYSQL_URL = \"mysql+pymysql://user:pass@host:3306/retail_bi?charset=utf8mb4\"\n```\n"
            "**Реальные данные.** Достаточно заполнить те же таблицы (или представления с теми же именами и полями) "
            "из хранилища — код страниц менять не нужно. Для полного объёма данных нужны агрегированные витрины "
            "в ClickHouse или MS SQL; запросы приложения уже агрегируют на стороне базы.")
    ui.export_panel("about")
